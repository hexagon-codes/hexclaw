// 使用应用捆绑或环境提供的真实引擎，缺少引擎时明确跳过实际转换验证。
func workflowOutputRenderTools(t *testing.T) (string, string) {
	t.Helper()
	find := func(name string) string {
		if root := os.Getenv("HEXCLAW_RENDER_BIN_DIR"); root != "" {
			arch := runtime.GOARCH
			if arch == "arm64" {
				arch = "aarch64"
			} else if arch == "amd64" {
				arch = "x86_64"
			}
			for _, leaf := range []string{name, name + "-" + arch + "-apple-darwin"} {
				path := filepath.Join(root, leaf)
				if info, err := os.Stat(path); err == nil && !info.IsDir() {
					return path
				}
			}
		}
		path, _ := exec.LookPath(name)
		return path
	}
	pandoc, typst := find("pandoc"), find("typst")
	if pandoc == "" || typst == "" {
		t.Skip("Actual workflow document rendering requires pandoc and typst")
	}
	return pandoc, typst
}

func setWorkflowOutputRenderer(t *testing.T, s *Server, pandoc, typst string) {
	t.Helper()
	// Pandoc按引擎名查找typst，和桌面装配一样提供不带平台后缀的工具名。
	tools := t.TempDir()
	if err := os.Symlink(typst, filepath.Join(tools, "typst")); err != nil {
		t.Fatal(err)
	}
	t.Setenv("PATH", tools+string(os.PathListSeparator)+os.Getenv("PATH"))
	renderer, err := render.NewPandocRenderer(pandoc, typst, t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	s.renderSvc, err = render.NewService(render.ServiceConfig{Renderer: renderer})
	if err != nil {
		t.Fatal(err)
	}
}

